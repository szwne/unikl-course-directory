/* ===================================================== 
   ELEMENTS 
===================================================== */ 
 
const courseList = document.getElementById("courseList"); 
const courseCount = document.getElementById("courseCount"); 
 
const searchInput = document.getElementById("searchInput"); 
const searchButton = document.getElementById("searchButton"); 
 
const searchMessage = document.getElementById("searchMessage"); 
 
 
/* ===================================================== 
   DISPLAY COURSES 
===================================================== */ 
 
function displayCourses(courseArray) { 
 
    courseList.innerHTML = ""; 
 
    courseCount.textContent = courseArray.length; 
 
 
    if (courseArray.length === 0) { 
 
        courseList.innerHTML = ` 
            <div class="no-results"> 
 
                <h3>No courses found</h3> 
 
                <p> 
                    Try searching using a different course 
                    name or course code. 
                </p> 
 
            </div> 
        `; 
 
        return; 
    } 
 
 
    courseArray.forEach(course => { 
 
        const courseCard = document.createElement("div"); 
 
        courseCard.className = "course-card"; 
 
 
        courseCard.innerHTML = ` 
 
            <div class="course-information"> 
 
                <span class="course-code"> 
                    ${course.code} 
                </span> 
 
                <h3 class="course-name"> 
                    ${course.name} 
                </h3> 
 
                <p class="course-category"> 
                    ${course.category} 
                </p> 
 
            </div> 
 
 
            <div class="course-actions"> 
 
                <a 
                    href="${course.pdf}" 
                    class="view-syllabus-button" 
                    target="_blank" 
                    rel="noopener noreferrer"
                > 
                    View Syllabus 
                </a> 
 
                <a 
                    href="${course.pdf}" 
                    class="download-syllabus-button" 
                    download
                > 
                    Download PDF 
                </a> 
 
            </div> 
 
        `; 
 
 
        courseList.appendChild(courseCard); 
 
    }); 
 
} 


/* =====================================================
   CATEGORY FILTER
===================================================== */

const categoryCards = document.querySelectorAll(".category-card");

categoryCards.forEach(card => {

    card.addEventListener("click", function () {

        const categoryName =
            this.querySelector("h3").textContent.trim();

        const filteredCourses = courses.filter(course =>
            course.category === categoryName
        );

        searchInput.value = "";

        searchMessage.textContent =
            `Showing courses in "${categoryName}"`;

        displayCourses(filteredCourses);

        document.getElementById("courses").scrollIntoView({
            behavior: "smooth"
        });

    });

});


/* =====================================================
   VIEW ALL COURSES
===================================================== */

const allCoursesLink = document.getElementById("allCoursesLink");

allCoursesLink.addEventListener("click", function () {

    searchInput.value = "";

    searchMessage.textContent = "";

    displayCourses(courses);

});


/* ===================================================== 
   SEARCH 
===================================================== */ 
 
function performSearch(shouldScroll = false) { 
 
    const searchTerm = searchInput.value 
        .toLowerCase() 
        .trim(); 
 
 
    if (searchTerm === "") { 
 
        searchMessage.textContent = ""; 
 
        displayCourses(courses); 
 
        return; 
    } 
 
 
    const filteredCourses = courses.filter(course => { 
 
        return ( 
            course.code.toLowerCase().includes(searchTerm) || 
            course.name.toLowerCase().includes(searchTerm) 
        ); 
 
    }); 
 
 
    searchMessage.textContent = 
        `Search results for "${searchInput.value}"`; 
 
 
    displayCourses(filteredCourses); 
 
 
    /* AUTO SCROLL ONLY WHEN SEARCH IS SUBMITTED */
 
    if (shouldScroll) {
 
        document.getElementById("courses").scrollIntoView({
            behavior: "smooth"
        });
 
    }
 
} 
 
 
/* ===================================================== 
   SEARCH BUTTON 
===================================================== */ 
 
searchButton.addEventListener( 
    "click", 
    function() {
        performSearch(true);
    }
); 
 
 
/* ===================================================== 
   SEARCH WHILE TYPING 
===================================================== */ 
 
searchInput.addEventListener( 
    "input", 
    function() {
        performSearch(false);
    }
); 
 
 
/* ===================================================== 
   ENTER KEY 
===================================================== */ 
 
searchInput.addEventListener( 
    "keydown", 
    function(event) { 
 
        if (event.key === "Enter") { 
 
            event.preventDefault();
            performSearch(true); 
 
        } 
 
    } 
); 
 
 
